package com.alo.downloader.core.cookie

import com.alo.downloader.core.model.Platform
import com.alo.downloader.core.router.PlatformResolver

/** One cookie, as stored in a Netscape `cookies.txt` line. */
data class CookieEntry(
    val domain: String,
    val includeSubdomains: Boolean,
    val path: String,
    val secure: Boolean,
    /** Epoch seconds; 0 means a session cookie. */
    val expiresAt: Long,
    val name: String,
    val value: String,
    val httpOnly: Boolean = false,
) {
    fun isExpired(nowSeconds: Long): Boolean = expiresAt in 1 until nowSeconds
}

/**
 * Reads and writes the Netscape cookie file format understood by both yt-dlp and gallery-dl,
 * and converts cookies captured from a WebView (`name=value; name2=value2`).
 */
object NetscapeCookies {
    const val HEADER = "# Netscape HTTP Cookie File"
    private const val HTTP_ONLY_PREFIX = "#HttpOnly_"

    fun parse(text: String): List<CookieEntry> = text.lineSequence().mapNotNull(::parseLine).toList()

    private fun parseLine(raw: String): CookieEntry? {
        var line = raw.trimEnd('\r', '\n')
        var httpOnly = false
        if (line.startsWith(HTTP_ONLY_PREFIX)) {
            httpOnly = true
            line = line.removePrefix(HTTP_ONLY_PREFIX)
        }
        if (line.isBlank() || line.startsWith("#")) return null
        val parts = line.split('\t')
        if (parts.size < 7) return null
        val domain = parts[0].trim()
        if (domain.isEmpty()) return null
        return CookieEntry(
            domain = domain,
            includeSubdomains = parts[1].equals("TRUE", ignoreCase = true),
            path = parts[2].ifEmpty { "/" },
            secure = parts[3].equals("TRUE", ignoreCase = true),
            expiresAt = parts[4].trim().toDoubleOrNull()?.toLong() ?: 0L,
            name = parts[5],
            // Values may legitimately contain tabs in broken exports; keep the rest of the line.
            value = parts.drop(6).joinToString("\t"),
            httpOnly = httpOnly,
        )
    }

    fun serialize(cookies: List<CookieEntry>): String = buildString {
        append(HEADER).append('\n')
        append("# Generated by ALO Downloader. Do not share this file.\n\n")
        for (c in cookies) {
            if (c.httpOnly) append(HTTP_ONLY_PREFIX)
            append(c.domain).append('\t')
            append(if (c.includeSubdomains) "TRUE" else "FALSE").append('\t')
            append(c.path).append('\t')
            append(if (c.secure) "TRUE" else "FALSE").append('\t')
            append(c.expiresAt).append('\t')
            append(c.name).append('\t')
            append(c.value).append('\n')
        }
    }

    /**
     * Converts a `Cookie:` header style string (what Android's `CookieManager.getCookie`
     * returns) into entries for [host]. The WebView does not expose expiry dates, so the
     * cookies get a fixed lifetime; the site will reject them once they are really stale.
     */
    fun fromHeader(header: String?, host: String, nowSeconds: Long, lifetimeSeconds: Long = DEFAULT_LIFETIME): List<CookieEntry> {
        if (header.isNullOrBlank()) return emptyList()
        val domain = "." + host.removePrefix("www.").trimStart('.')
        return header.split(';').mapNotNull { part ->
            val idx = part.indexOf('=')
            if (idx <= 0) return@mapNotNull null
            val name = part.substring(0, idx).trim()
            val value = part.substring(idx + 1).trim()
            if (name.isEmpty()) return@mapNotNull null
            CookieEntry(domain, true, "/", true, nowSeconds + lifetimeSeconds, name, value)
        }
    }

    /** Assigns every cookie to the platform its domain belongs to; unknown domains go to GENERIC. */
    fun groupByPlatform(cookies: List<CookieEntry>): Map<Platform, List<CookieEntry>> =
        cookies.groupBy { PlatformResolver.fromCookieDomain(it.domain) }

    /** Later entries with the same domain/path/name replace earlier ones. */
    fun merge(existing: List<CookieEntry>, incoming: List<CookieEntry>): List<CookieEntry> {
        val map = LinkedHashMap<Triple<String, String, String>, CookieEntry>()
        (existing + incoming).forEach { map[Triple(it.domain.trimStart('.'), it.path, it.name)] = it }
        return map.values.toList()
    }

    fun hasAuthCookie(platform: Platform, cookies: List<CookieEntry>, nowSeconds: Long): Boolean =
        platform.authCookies.isEmpty() && cookies.isNotEmpty() ||
            cookies.any { c -> c.name in platform.authCookies && !c.isExpired(nowSeconds) && c.value.isNotBlank() }

    const val DEFAULT_LIFETIME: Long = 180L * 24 * 3600
}
